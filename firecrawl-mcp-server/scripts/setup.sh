#!/usr/bin/env bash
# Create .env with a generated MCP bearer token and the default host port. Non-interactive;
# secrets are never printed.
#   scripts/setup.sh                       create .env WITHOUT a token (auth off, loopback only)
#   scripts/setup.sh --with-token          create .env with a generated MCP_AUTH_TOKEN
#   scripts/setup.sh --force [--with-token]  rewrite an existing .env (backs up the old file)
# A valid existing .env is left unchanged unless --force is given.
set -euo pipefail
# shellcheck source=lib/common.sh
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib/common.sh"

force=0
with_token=0
for arg in "$@"; do
  case "${arg}" in
    --force) force=1 ;;
    --with-token) with_token=1 ;;
    -h | --help)
      echo "usage: scripts/setup.sh [--force] [--with-token]"
      exit 0
      ;;
    *) die "unknown option: ${arg} (usage: scripts/setup.sh [--force] [--with-token])" ;;
  esac
done

generate_token() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex 32
  else
    head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n'
  fi
}

if [ -f "${ENV_FILE}" ] && [ "${force}" -eq 0 ]; then
  check_env
  info ".env already exists and looks valid; left unchanged (use --force to regenerate)."
  exit 0
fi

if [ -f "${ENV_FILE}" ]; then
  backup="${ENV_FILE}.bak-$(date +%Y%m%d-%H%M%S)"
  cp -p "${ENV_FILE}" "${backup}"
  info "Backed up the old .env to $(basename "${backup}") (git-ignored; delete it when no longer needed)"
fi

umask 077
TMP_FILE="$(mktemp "${ROOT_DIR}/.env.XXXXXX")"
trap 'rm -f "${TMP_FILE}"' EXIT
{
  printf '# Generated by scripts/setup.sh. Git-ignored; never commit or share this file.\n'
  if [ "${with_token}" -eq 1 ]; then
    printf 'MCP_AUTH_TOKEN=%s\n' "$(generate_token)"
  else
    printf '# MCP_AUTH_TOKEN is unset: /mcp needs no auth (loopback-only). Re-run with --force --with-token to enable.\n'
  fi
  printf 'HOST_PORT=%s\n' "${DEFAULT_PORT}"
  printf '# Self-hosted Firecrawl API on the firecrawl_backend network.\n'
  printf 'FIRECRAWL_API_URL=http://api:3002\n'
} >"${TMP_FILE}"
mv -f "${TMP_FILE}" "${ENV_FILE}"
trap - EXIT
chmod 600 "${ENV_FILE}" 2>/dev/null || true

check_env
if [ "${with_token}" -eq 1 ]; then
  info "Wrote ${ENV_FILE} (token generated, not shown; copy it from .env into Goose)."
else
  info "Wrote ${ENV_FILE} (no token: /mcp is unauthenticated on loopback)."
fi
printf '\nNext step:\n  scripts/start.sh   (builds and starts the server, then prints the Goose config)\n'
